import type { ShapeVariant } from "@/components/shapes"

/**
 * A background shape as Figma draws it: the variant, the center (x, y) and size (w, h) of the layer in px of its frame
 * and its rotation in degrees. Extracted with the Plugin API from the layers' transforms: the bounding boxes Figma
 * exports for rotated layers aren't centered on them.
 *
 * Figma's sections and footer clip the shapes they hold. That is left out: there the cut is hidden by the next
 * section, while the page has one continuous background, where it would be a hard line across the blurred shapes.
 */
export type FigmaShape = readonly [variant: ShapeVariant, x: number, y: number, w: number, h: number, rotate: number]

/** A page as drawn in Figma: everything above `footer` is behind the content, the rest is behind the footer */
export type FigmaFrame = {
  width: number
  height: number
  footer: number
  shapes: readonly FigmaShape[]
}

