import { execFileSync } from "node:child_process"
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import path from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const projectRoot = path.resolve(__dirname, "..")
const sourceLogo = path.join(projectRoot, "public/polinetwork_logo.png")
const outFile = path.join(projectRoot, "src/components/cfu-game/logoData.ts")

const tmpDir = mkdtempSync(path.join(tmpdir(), "cfu-logo-"))
const resized = path.join(tmpDir, "logo256.png")

try {
  execFileSync("sips", ["-Z", "256", sourceLogo, "--out", resized], {
    stdio: "pipe",
  })

  const buffer = readFileSync(resized)
  const base64 = buffer.toString("base64")
  const dataUri = `data:image/png;base64,${base64}`

  const contents = `// Generated by scripts/make-logo-data.mjs — do not edit by hand.
// Source: public/polinetwork_logo.png, resized to 256px via \`pnpm gen:logo\`.
export const POLINETWORK_LOGO_DATA_URI = "${dataUri}"
`

  writeFileSync(outFile, contents, "utf8")

  const kb = (buffer.length / 1024).toFixed(1)
  console.log(`Logo base64 generato: ${outFile} (${kb} KB sorgente PNG)`)
} finally {
  rmSync(tmpDir, { recursive: true, force: true })
}
